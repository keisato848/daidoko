/**
 * 賞味期限は**行に 1 つだけ**持ち、合算時は**近い方（早い日付）を残す**（v13）。
 *
 * 在庫は同じ品目を 1 行にまとめて数量を合算するので、買った回ごとの期限は持てない。
 * 先に使い切るのは古い方なので、早い日付を残せば「そろそろ使ったほうがいい」の判断に足りる。
 * ロット分割（買った回ごとに行を分ける）は、合算をやめる代償が大きすぎるため採らなかった。
 */
import { nearerExpiry } from '../pantry.service';

describe('賞味期限のマージ', () => {
  it('早い日付を残す（先に使い切る方に合わせる）', () => {
    expect(nearerExpiry('2026-09-30', '2026-09-01')).toBe('2026-09-01');
    expect(nearerExpiry('2026-09-01', '2026-09-30')).toBe('2026-09-01');
  });

  it('片方が未設定なら入っている方を採る（入れた情報を捨てない）', () => {
    expect(nearerExpiry(null, '2026-09-01')).toBe('2026-09-01');
    expect(nearerExpiry('2026-09-01', null)).toBe('2026-09-01');
  });

  it('どちらも未設定なら未設定のまま（任意入力なので勝手に埋めない）', () => {
    expect(nearerExpiry(null, null)).toBeNull();
  });

  it('同じ日付ならそのまま', () => {
    expect(nearerExpiry('2026-09-01', '2026-09-01')).toBe('2026-09-01');
  });

  it('年をまたぐ比較でも文字列比較で正しい（YYYY-MM-DD 前提）', () => {
    expect(nearerExpiry('2027-01-01', '2026-12-31')).toBe('2026-12-31');
  });
});
